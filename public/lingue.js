function salvata() {
  try {
    return localStorage.getItem("lingua");
  } catch {
    return null;
  }
}

function scegli() {
  const query = new URLSearchParams(location.search).get("lang");
  const hash = new URLSearchParams(location.hash.slice(1)).get("l");
  const browser = (navigator.languages?.[0] ?? navigator.language ?? "it").slice(0, 2).toLowerCase();
  return [query, hash, salvata(), browser].find((l) => LINGUE.includes(l)) ?? "it";
}

let corrente = scegli();
const ascoltatori = new Set();

export const lingua = () => corrente;
export const locale = () => LOCALI[corrente];

export function t(chiave, valori = {}) {
  const testo = TESTI[corrente][chiave] ?? TESTI.it[chiave] ?? chiave;
  return testo.replace(/\{(\w+)\}/g, (tutto, k) => (k in valori ? String(valori[k]) : tutto));
}

export const voce = (mappa, chiave) => mappa[chiave]?.[corrente] ?? mappa[chiave]?.it ?? chiave;
export const persone = (n) => `${n} ${n === 1 ? t("persona") : t("persone")}`;
export const servizio = (nome) => (corrente === "it" ? nome : SERVIZI[String(nome).trim().toLowerCase()]?.[corrente] ?? nome);

export function testoData(iso, opzioni = { weekday: "long", day: "numeric", month: "long" }) {
  return new Intl.DateTimeFormat(locale(), { ...opzioni, timeZone: "UTC" }).format(new Date(`${iso}T12:00:00Z`));
}

/** Testo tradotto da un oggetto {it, en, ...} o dalle traduzioni {en: {campo}} di un elemento del menù. */
export function tradotto(elemento, campo) {
  return (corrente !== "it" && elemento.traduzioni?.[corrente]?.[campo]) || elemento[campo] || "";
}

/** Applica i testi agli elementi con data-t, data-t-placeholder e data-t-aria. */
export function applicaTesti(radice = document) {
  document.documentElement.lang = corrente;
  for (const el of radice.querySelectorAll("[data-t]")) el.textContent = t(el.dataset.t);
  for (const el of radice.querySelectorAll("[data-t-placeholder]")) el.placeholder = t(el.dataset.tPlaceholder);
  for (const el of radice.querySelectorAll("[data-t-aria]")) el.setAttribute("aria-label", t(el.dataset.tAria));
}

export function quandoCambia(funzione) {
  ascoltatori.add(funzione);
}

export function impostaLingua(nuova) {
  if (!LINGUE.includes(nuova) || nuova === corrente) return;
  corrente = nuova;
  try {
    localStorage.setItem("lingua", nuova);
  } catch {}
  applicaTesti();
  for (const f of ascoltatori) f(nuova);
}

/** Pulsanti IT EN DE FR ES. */
export function selettoreLingua(contenitore) {
  const gruppo = document.createElement("div");
  gruppo.className = "lingue";
  gruppo.setAttribute("role", "group");
  const disegna = () => {
    gruppo.setAttribute("aria-label", t("lingua"));
    gruppo.replaceChildren(
      ...LINGUE.map((l) => {
        const b = document.createElement("button");
        b.type = "button";
        b.className = "lingua";
        b.textContent = l.toUpperCase();
        b.lang = l;
        b.title = NOMI[l];
        b.setAttribute("aria-label", NOMI[l]);
        b.setAttribute("aria-pressed", String(l === corrente));
        b.addEventListener("click", () => impostaLingua(l));
        return b;
      }),
    );
  };
  quandoCambia(disegna);
  disegna();
  contenitore.append(gruppo);
}
